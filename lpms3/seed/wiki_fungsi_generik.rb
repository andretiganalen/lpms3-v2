  - **Tata letak tabel di PDF.** Beberapa baris pada Nota memiliki tata letak yang ambigu. Penempatan *Divisi* untuk Bagian Project & Supply Planning, Fungsi Purna Jual, dan Fungsi Rendal Produksi ditafsirkan dari susunan tabel. Pastikan ke Bagian Business Process Management sebelum dipakai sebagai acuan resmi.
  - **Tanggal Nota.** Nota memuat dua tanggal: 24 Agustus 2026 (halaman utama dan lampiran) dan 05 Agustus 2026 (judul halaman 2), serta nomor "XXX" pada halaman 2. Halaman ini memakai tanggal 24 Agustus 2026 dan nomor 021/N/UQ/VIII/2026.
  - **Nama lama tetap sah.** Dokumen proses bisnis yang masih memakai nama lama tetap berlaku sampai direvisi (butir 1–3 Nota).
  - **Pemetaan detail.** Untuk pemetaan lengkap per unit dan tupoksi rinci, lihat dokumen Nota 021 (folder `docs/`).

